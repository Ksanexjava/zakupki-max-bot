TOKEN_RE = re.compile(r"[a-zа-я0-9/]+")


def normalize(text: str) -> str:
    return (text or "").lower().replace("ё", "е")


def tokens_of(text: str) -> list[str]:
    return TOKEN_RE.findall(normalize(text))


def _part_matches(part: str, joined: str, tokens: list[str]) -> bool:
    part = part.strip()
    if not part:
        return False
    if part.startswith("="):
        return part[1:] in tokens
    if " " in part:
        return part in joined
    return any(token.startswith(part) for token in tokens)


@dataclass(frozen=True)
class Rule:
    category_id: int
    parts: tuple[str, ...]
    order: int

    @property
    def weight(self) -> int:
        return len(self.parts)


def parse_keywords(category_id: int, keywords: str, order: int) -> list[Rule]:
    """«перчат+нитрил, бахил» -> правила для одной категории."""
    rules: list[Rule] = []
    for chunk in (keywords or "").split(","):
        parts = tuple(normalize(p).strip() for p in chunk.split("+") if p.strip())
        if parts:
            rules.append(Rule(category_id=category_id, parts=parts, order=order))
    return rules


def classify(name: str, rules: list[Rule]) -> int | None:
    """Возвращает id подходящей категории или None, если ничего не узнали."""
    joined = " ".join(tokens_of(name))
    tokens = joined.split()
    best: Rule | None = None
    for rule in rules:
        if all(_part_matches(part, joined, tokens) for part in rule.parts):
            if best is None or (rule.weight, -rule.order) > (best.weight, -best.order):
                best = rule
    return best.category_id if best else None
